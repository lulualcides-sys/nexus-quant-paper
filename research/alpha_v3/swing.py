"""ALPHA V3: fixed 8ATR target / 2ATR stop / max 12h holding period.

The V2 short-horizon economics were structurally poor. This is ONE economic
hypothesis adjustment applied consistently to all 10 candidate families.
Risk includes estimated both-side fees, spread and slippage; only a NEXT OPEN
may fill a time-exit generated by a bar close. No broker orders.
"""
from importlib import import_module
from research.alpha.run import BOTS
from research.alpha.engine import (
   History,build,check_candles,TAKER_FEE_BPS,HALF_SPREAD_BPS,START_USDT,RISK_FRACTION)
from research.alpha_v2.filters import ROUNDTRIP_BPS,BULLISH,RECOVERY
COST_TARGET_MULTIPLIER=3.0
TARGET_ATR=8.0
STOP_ATR=2.0
MAX_HOLD_MINUTES=720
MAX_VOL_ATR_RATIO=.018

class SwingFilter:
    def __init__(self,name):
        if name not in BOTS:raise ValueError("unapproved robot")
        self.name=name
        self.original=import_module("research.alpha.bots."+name)
        self.TIMEFRAME=self.original.TIMEFRAME

    def diagnose(self,h,f,i):
        if not self.original.signal(h,f,i):return "raw_no_signal"
        b=h[i];p=b["close"];atr=f["atr"][i]
        if p<=0 or atr<=0:return "bad_price_or_risk"
        target_bps=10000*TARGET_ATR*atr/p
        if target_bps<ROUNDTRIP_BPS*COST_TARGET_MULTIPLIER:
            return "target_cannot_cover_cost"
        vol_mean=f["vol_avg"][i-1]
        if vol_mean<=0 or b["volume"]<.8*vol_mean:
            return "weak_volume"
        if atr/p>MAX_VOL_ATR_RATIO:
            return "extreme_volatility"
        if i<240:return "regime_warmup"
        slow=f["ema200"][i]
        if self.name in BULLISH:
            if not (f["ema50"][i]>slow and slow>f["ema200"][i-24]):
                return "countertrend"
            if f["rsi"][i]>74:return "late_momentum"
        else:
            if not (f["ema50"][i]>=slow*.998 and slow>=f["ema200"][i-24]*.9995):
                return "bearish_regime"
            if f["rsi"][i]<16:return "capitulation"
        return "accepted"

    def signal(self,h,f,i):
        return self.diagnose(h,f,i)=="accepted"

def test_engine(bars,model,minutes,slip_bps=5.,features=None,capital=START_USDT):
    """Isolated monthly ledger. No carry-over or fake last-close liquidation."""
    check_candles(bars,minutes)
    if len(bars)<260:raise ValueError("too few bars")
    f=features if features is not None else build(bars)
    equity=capital;peak=equity;max_dd=0.
    trade=None;ledger=[];signal_count=0;order_count=0;incomplete_positions=0
    def finish(raw,ts,reason):
        nonlocal equity,trade
        p=trade
        exit_price=raw*(1-(HALF_SPREAD_BPS+slip_bps)/10000.)
        gross=(raw-p["entry_raw"])*p["qty"]
        net=(exit_price-p["entry"])*p["qty"]-TAKER_FEE_BPS/10000*p["qty"]*(exit_price+p["entry"])
        equity+=net
        ledger.append(dict(
          signal_ts_utc=_iso(p["signal_ts"]),entry_ts_utc=_iso(p["entry_ts"]),
          exit_ts_utc=_iso(ts),side="LONG",
          entry_raw=round(p["entry_raw"],6),entry=round(p["entry"],6),
          exit_raw=round(raw,6),exit=round(exit_price,6),qty=round(p["qty"],9),
          gross_usdt=round(gross,6),costs_usdt=round(gross-net,6),
          net_usdt=round(net,6),reason=reason,slippage_bps_per_side=slip_bps))
        trade=None

    for i in range(241,len(bars)):
        b=bars[i];exited=False
        # Prior completed candle generated a time exit: fill NEXT bar open.
        if trade is not None and trade["exit_next_open"]:
            finish(b["open"],b["time"],"time_next_open")
            exited=True
        if trade is None and not exited and i>241 and model.signal(History(bars,i),f,i-1):
            signal_count+=1
            atr=f["atr"][i-1]
            raw=b["open"]
            entry=raw*(1+(HALF_SPREAD_BPS+slip_bps)/10000.)
            # Stop/target use ATR frozen at signal close (not future candle).
            distance=max(STOP_ATR*atr,raw*.001)
            stop=entry-distance
            target=entry+TARGET_ATR*atr
            worst_exit=stop*(1-(HALF_SPREAD_BPS+slip_bps)/10000.)
            fee_rate=TAKER_FEE_BPS/10000.
            full_unit_risk=(entry-worst_exit)+fee_rate*(entry+worst_exit)
            if stop>0 and target>entry and full_unit_risk>0 and equity>0:
                qty=min(equity*RISK_FRACTION/full_unit_risk,
                        equity*.98/(entry*(1+fee_rate)))
                if qty>0:
                    order_count+=1
                    trade=dict(entry_ts=b["time"],signal_ts=bars[i-1]["time"]+minutes*60,
                               entry_raw=raw,entry=entry,stop=stop,target=target,
                               qty=qty,held=0,exit_next_open=False)
        if trade is not None:
            trade["held"]+=1
            p=trade
            if b["low"]<=p["stop"]:
                exit_raw=min(b["open"],p["stop"]) if p["held"]>1 else p["stop"]
                why="ambiguous_stop_first" if b["high"]>=p["target"] else "stop"
                finish(exit_raw,b["time"]+minutes*60,why)
            elif b["high"]>=p["target"]:
                finish(p["target"],b["time"]+minutes*60,"target")
            elif p["held"]*minutes>=MAX_HOLD_MINUTES:
                p["exit_next_open"]=True
        marked=equity if trade is None else equity+(b["close"]-trade["entry"])*trade["qty"]
        peak=max(peak,marked)
        max_dd=max(max_dd,(peak-marked)/peak if peak>0 else 1.)
    if trade is not None:
        incomplete_positions=1
    return dict(ledger=ledger,equity=equity,max_drawdown_pct=round(max_dd*100,5),
                signals_seen=signal_count,orders_filled=order_count,
                open_at_period_end=incomplete_positions,
                final_open_mark_to_market_usdt=None if trade is None else
                      round((bars[-1]["close"]-trade["entry"])*trade["qty"],4))

def _iso(ts):
    from datetime import datetime,timezone
    return datetime.fromtimestamp(ts,timezone.utc).isoformat()
