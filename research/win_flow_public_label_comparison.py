"""Frozen independent WIN flow detector versus public Tracker promo labels.

Requires audited LOCAL M1+ticks generated by win_mt5_tick_provenance.py.
Optionally reads PUBLIC promotional markers explicitly embedded on Greenhouse's
open offer page. This does not identify or copy the proprietary Tracker source.
Never send locally collected broker history to this site or GitHub.

Labels are curated hindsight and cannot establish precision, absence of
repainting or live expectancy. No trade execution/optimization.
"""
from __future__ import annotations

import argparse
import json
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

from research.win_flow_exhaustion_reference import (
    ResearchPolicy,price_candidate,fibonacci_levels
)

SP=ZoneInfo("America/Sao_Paulo")
PUBLIC_URL="https://lojadagreenhouse.com.br/ofertatracker/"
POLICY=ResearchPolicy() # Frozen before examination of terminal data.

def local_label_minute(timestamp):
    dt=datetime.fromtimestamp(int(timestamp),timezone.utc).astimezone(SP)
    return dt.date().isoformat(),dt.hour*60+dt.minute

def independent_signals(quality_rows,policy=POLICY):
    """No future candles, no unverified tick data; signaling only after close."""
    if not quality_rows:
        return [],{"valid":0,"invalid":0,"price_candidates":0,
                   "rejected_due_to_tick_quality":0}
    ordered=sorted(quality_rows,key=lambda x:x["time"])
    if any(ordered[i]["time"]<=ordered[i-1]["time"] for i in range(1,len(ordered))):
        raise ValueError("Duplicate/out-of-order private data")
    bars=[{k:b[k] for k in ("time","open","high","low","close","real_volume")} for b in ordered]
    stats={
        "valid":sum(bool(x["valid_flow"]) for x in ordered),
        "invalid":sum(not x["valid_flow"] for x in ordered),
        "price_candidates":0,
        "rejected_due_to_tick_quality":0,
        "rejected_contra_delta":0,
        "candidate_signals":[]}
    for i in range(len(ordered)):
        # Never treat a non-contiguous 20-bar history as a continuous setup.
        if i>=policy.lookback and ordered[i]["time"]-ordered[i-policy.lookback]["time"]!=policy.lookback*60:
            continue
        side=price_candidate(bars,i,policy)
        if side is None: continue
        stats["price_candidates"]+=1
        bar=ordered[i]
        if not bar["valid_flow"]:
            stats["rejected_due_to_tick_quality"]+=1
            continue
        # The reference detector needs heavy sell aggressors for BUY reversals,
        # heavy buy aggressors for SELL. This is NOT the original Tracker formula.
        buy=bar.get("buy_volume")
        sell=bar.get("sell_volume")
        classified=(buy or 0)+(sell or 0)
        if (buy is None or sell is None or classified<=0
            or bar["classified_trade_count"]<policy.min_classified_events
            or bar["classified_share"]<policy.min_classified_share):
            stats["rejected_due_to_tick_quality"]+=1
            continue
        contra=(sell/classified if side==1 else buy/classified)
        if contra<policy.contra_aggressor_share:
            stats["rejected_contra_delta"]+=1
            continue
        # Important: candle's published open time is NOT time when signal is
        # visible to an operator. Earliest availability is NEXT minute.
        date,minute=local_label_minute(bar["time"]+60)
        stats["candidate_signals"].append({
            "observed_after_closed_bar_utc":int(bar["time"])+60,
            "reference_bar_open_utc":int(bar["time"]),
            "date":date,"minute":minute,
            "side":side,"contra_share":round(contra,4),
            "delta":bar["delta"],
            "price_levels":fibonacci_levels(bar,side),
            "source":"NQ_INDEPENDENT_EXHAUSTION_NOT_TRACKER"
        })
    return stats["candidate_signals"],{
        k:v for k,v in stats.items() if k!="candidate_signals"
    }

def public_markers_from_html(html):
    from research.greenhouse_public_gallery_decode import decode_literal
    rows=decode_literal(html)["s"]
    days=["2026-11-03","2026-11-04"]
    labels=[]
    for r in rows:
        if len(r)<4:raise ValueError("Invalid promo record")
        if r[1] not in (0,1) or r[3] not in ("c","v"):
            raise ValueError("Unknown public label day or direction")
        labels.append({
            "id":int(r[0]),"date":days[int(r[1])],
            "minute":int(r[2]),"side":1 if r[3]=="c" else -1
        })
    return labels

def compare(signals,labels,tolerance_minutes=1):
    """Greedy unique pairing; exact-first within ±1 min, no P&L inference."""
    if tolerance_minutes not in (0,1):
        raise ValueError("Tolerance restricted to 0 or 1 minute")
    matching=set()
    paired=[]
    for offset in ([0] if tolerance_minutes==0 else [0,-1,1]):
        for i,s in enumerate(signals):
            if i in matching:continue
            for j,label in enumerate(labels):
                if any(p["promo_id"]==label["id"] for p in paired):
                    continue
                if (s["date"]==label["date"] and s["side"]==label["side"] and
                    s["minute"]+offset==label["minute"]):
                    paired.append({"local_signal_index":i,"promo_id":label["id"],
                                   "timing_offset_minutes":offset})
                    matching.add(i)
                    break
    return {
        "status":"PUBLIC_PROMOTIONAL_MARKER_OVERLAP_NOT_TRACKER_EQUIVALENCE",
        "matching_tolerance_minutes":tolerance_minutes,
        "independent_signals":len(signals),"marketing_labels":len(labels),
        "matched_unique_labels":len(paired),
        "unpaired_signals_not_verified_false_positives":len(signals)-len(paired),
        "unpaired_marketing_labels_not_verified_false_negatives":len(labels)-len(paired),
        "matches":paired,"approved_for_live":False,
        "warning":"Marketing labels are curated and may not be exact signal timestamps; no causality, fills, volume feed, or profitability proof."
    }

def main():
    p=argparse.ArgumentParser(description="Compare local audited classified-flow signals with public commercial labels; no trades")
    p.add_argument("--input",action="append",required=True,
                   help="Your locally saved WINZ26_YYYY-MM-DD_flow_audit.json; repeat for dates")
    p.add_argument("--public-html",default=None,
                   help="Optional previously saved public offer HTML; no network if provided")
    p.add_argument("--fetch-public-html",action="store_true",
                   help="Only downloads public promo HTML, never uploads broker records")
    p.add_argument("--out",default="private_mt5/nq_public_labels_comparison.json")
    args=p.parse_args()
    if not args.public_html and not args.fetch_public_html:
        p.error("Specify --public-html or --fetch-public-html")
    rows=[]
    audit=[]
    for source in args.input:
        d=json.loads(Path(source).read_text(encoding="utf-8"))
        if "minutes" not in d or "quality" not in d:
            raise ValueError("Not a local quality audit from win_mt5_tick_provenance")
        q=d["quality"]
        if q["contract"]!="WINZ26" or q["status"]!="LOCAL_BROKER_HISTORY_ONLY_NOT_TRACKER_OR_B3_ATTESTED":
            raise ValueError("Use genuine matching WINZ26 explicit-expiry history")
        audit.append({k:q[k] for k in ("date","candles","valid_flow_minutes","rejected_minutes")})
        rows.extend(d["minutes"])
    if args.public_html:
        markup=Path(args.public_html).read_text(encoding="utf-8")
    else:
        req=urllib.request.Request(PUBLIC_URL,headers={"User-Agent":"NexusQuantPublicResearch/1.0"})
        with urllib.request.urlopen(req,timeout=30) as r:
            markup=r.read(1_000_000).decode("utf-8-sig")
    public=public_markers_from_html(markup)
    requested_days={x["date"] for x in audit}
    public=[label for label in public if label["date"] in requested_days]
    signals,checks=independent_signals(rows)
    results={
        "status":"FROZEN_MODEL_LOCAL_DATA_COMPARED_WITH_PUBLIC_PROMOTIONAL_LABELS",
        "version":"1.0","source_quality":audit,"candle_quality":checks,
        "exact_minute":compare(signals,public,0),
        "plus_or_minus_one_minute":compare(signals,public,1),
        "model_parameters_not_fit_to_promo":POLICY.__dict__,
        "signals":signals,
        "no_broker_orders":True,"original_tracker_not_recovered":True,
        "no_profitability_demonstrated":True
    }
    target=Path(args.out).resolve()
    if "private_mt5" not in target.parts:
        raise ValueError("Only private_mt5 folder outputs allowed; not a GitHub repository public path")
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(json.dumps(results,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print("MODEL_NOT_ORIGINAL_TRACKER")
    print(json.dumps({"input_days":audit,"quality":checks,
        "exact_matches":results["exact_minute"]["matched_unique_labels"],
        "one_minute_matches":results["plus_or_minus_one_minute"]["matched_unique_labels"],
        "private_result":str(target)},ensure_ascii=False,indent=2))

if __name__=="__main__":main()
